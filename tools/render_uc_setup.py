"""Render the Unity Catalog setup SQL from a validated inventory.

  python tools/render_uc_setup.py --inventory config/inventory.json --output build/uc_setup.sql \
      --job-principal '<application-id-of-job-identity>' [--consumer-group analysts]

Creates the control schema and tables, the target schemas and every target
table with its explicit schema. Tables are created IF NOT EXISTS; the nightly
job never creates or alters tables, it only overwrites data, and it refuses to
write into a table whose schema differs from the inventory.
Run the output in a SQL warehouse as a user who can create schemas and grant.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from bridge import contract  # noqa: E402

CONTROL_TABLES = {
    "table_log": "release_id STRING, job_run_id STRING, mapping_id STRING, target STRING, mandatory BOOLEAN, "
                 "attempt_id STRING, status STRING, source_rows BIGINT, parquet_rows BIGINT, written_rows BIGINT, "
                 "delta_version BIGINT, stage_path STRING, detail STRING, event_utc TIMESTAMP, "
                 "method STRING, error_code INT, duration_seconds DOUBLE, count_source STRING, commit_utc TIMESTAMP",
    "run_log": "release_id STRING, job_run_id STRING, event STRING, business_date DATE, upstream_run_id STRING, "
               "upstream_sequence BIGINT, inventory_version STRING, detail STRING, event_utc TIMESTAMP",
    "plan": "job_run_id STRING, release_id STRING, batch_id INT, position INT, mapping_id STRING, "
            "mandatory BOOLEAN, business_date DATE, upstream_sequence BIGINT, cutoff_utc TIMESTAMP, "
            "planned_utc TIMESTAMP, expected_rows BIGINT, count_source STRING, source_schema_hash STRING",
}


def principal(p):
    if not p or "`" in p:
        raise ValueError(f"Unsafe principal {p!r}")
    return f"`{p}`"


def render(doc, job_principal, consumer_group=None):
    contract.validate_inventory(doc)
    problems = contract.variant_4a_problems(doc)
    if problems:
        raise ValueError("; ".join(problems))
    q = contract.q_spark
    ctl = doc["control"]
    cc, cs = q(ctl["catalog"]), q(ctl["schema"])
    jp = principal(job_principal)
    props = doc.get("table_properties", contract.DEFAULT_TABLE_PROPERTIES)
    tblprops = ", ".join(f"'{k}' = '{v}'" for k, v in sorted(props.items()))
    out = ["-- Generated by tools/render_uc_setup.py from inventory "
           f"{doc['inventory_version']}. Safe to re-run (IF NOT EXISTS).", "",
           "-- Control schema and append-only logs",
           f"CREATE SCHEMA IF NOT EXISTS {cc}.{cs};"]
    for name, cols in CONTROL_TABLES.items():
        out.append(f"CREATE TABLE IF NOT EXISTS {cc}.{cs}.{q(name)} ({cols});")
    out += [
        f"CREATE OR REPLACE VIEW {cc}.{cs}.`table_latest` AS",
        "SELECT * EXCEPT (rn) FROM (SELECT *, row_number() OVER (",
        "  PARTITION BY release_id, mapping_id ORDER BY event_utc DESC) AS rn",
        f"  FROM {cc}.{cs}.`table_log`) WHERE rn = 1;",
        f"CREATE OR REPLACE VIEW {cc}.{cs}.`table_current` AS",
        "SELECT * EXCEPT (rn) FROM (SELECT *, row_number() OVER (",
        "  PARTITION BY mapping_id ORDER BY event_utc DESC) AS rn",
        f"  FROM {cc}.{cs}.`table_log` WHERE status IN ('PUBLISHED','ALREADY_CURRENT','ROLLED_BACK')) WHERE rn = 1;",
        f"GRANT USE SCHEMA, SELECT, MODIFY ON SCHEMA {cc}.{cs} TO {jp};",
        ""]

    schemas = sorted({(m["target_catalog"], m["target_schema"]) for m in doc["mappings"]})
    catalogs = sorted({ctl["catalog"]} | {c for c, _ in schemas})
    out.append("-- Catalog access")
    out += [f"GRANT USE CATALOG ON CATALOG {q(c)} TO {jp};" for c in catalogs]
    out += ["-- Serverless JDBC fallback reads Synapse through this Unity Catalog connection.",
            f"GRANT USE CONNECTION ON CONNECTION {q(doc['synapse']['uc_jdbc_connection'])} TO {jp};"]
    out += ["-- Staging: the job reads CETAS output through a UC external location on the staging container.",
            "-- The JDBC fallback also WRITES its Parquet under staging.root, so the job needs WRITE FILES too.",
            "-- Reuse the existing external location; create one only if none covers this container:",
            "-- CREATE EXTERNAL LOCATION IF NOT EXISTS `bridge_stage` URL '" + doc["staging"]["root"] + "/'",
            "--   WITH (STORAGE CREDENTIAL `<storage-credential>`);",
            f"-- GRANT READ FILES, WRITE FILES ON EXTERNAL LOCATION `<existing-location>` TO {jp};",
            "-- The plan reads the upstream row-count manifest: READ FILES on its location too.", ""]
    out.append("-- Target schemas")
    for c, s in schemas:
        out.append(f"CREATE SCHEMA IF NOT EXISTS {q(c)}.{q(s)};")
        out.append(f"GRANT USE SCHEMA ON SCHEMA {q(c)}.{q(s)} TO {jp};")
        if consumer_group:
            out.append(f"GRANT USE SCHEMA, SELECT ON SCHEMA {q(c)}.{q(s)} TO {principal(consumer_group)};")
    out.append("")
    out.append("-- Target tables (the job may only read and overwrite these)")
    for m in doc["mappings"]:
        cols = [f"  {q(c['name'])} {c['target_type'].upper()}" for c in contract.columns(m)]
        cols += [f"  {q(n)} {t.upper()} COMMENT 'set by the nightly bridge'" for n, t in contract.METADATA_COLUMNS]
        target = contract.fq_target(m)
        out.append(f"CREATE TABLE IF NOT EXISTS {target} (\n" + ",\n".join(cols) + "\n)")
        out.append(f"COMMENT 'Nightly full refresh of Synapse {m['source_schema']}.{m['source_object']}'")
        out.append(f"TBLPROPERTIES ({tblprops});")
        # SELECT + MODIFY cover read, INSERT OVERWRITE, DESCRIBE HISTORY and RESTORE.
        # Unity Catalog has no READ METADATA privilege (legacy Hive ACLs only):
        # granting it fails the script at the first target.
        out.append(f"GRANT SELECT, MODIFY ON TABLE {target} TO {jp};")
        out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inventory", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--job-principal", required=True)
    ap.add_argument("--consumer-group")
    a = ap.parse_args()
    doc = contract.load_inventory(a.inventory)
    Path(a.output).parent.mkdir(parents=True, exist_ok=True)
    Path(a.output).write_text(render(doc, a.job_principal, a.consumer_group))
    print(f"Wrote {a.output} ({len(doc['mappings'])} tables)")


if __name__ == "__main__":
    main()
